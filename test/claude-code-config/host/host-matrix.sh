#!/usr/bin/env bash
# Runs the scenario suite with the host ~/.claude missing, empty and holding
# DUMMY credentials, by pointing HOME at throwaway directories. The feature
# mounts nothing from the host, so all three must behave identically, and the
# throwaway "host" dirs must be left untouched.
set -uo pipefail
source "$(dirname "$0")/lib.sh"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
DOCKER_CONFIG="${DOCKER_CONFIG:-$HOME/.docker}"; export DOCKER_CONFIG
mkdir -p "$WORK/missing" "$WORK/empty/.claude" "$WORK/creds/.claude"
printf '{"claudeAiOauth":{"accessToken":"DUMMY-HOST"}}' > "$WORK/creds/.claude/.credentials.json"
chmod 600 "$WORK/creds/.claude/.credentials.json"
# Only the ~/.claude dirs matter (the devcontainer CLI may write its own cache under HOME).
snap() { (cd "$WORK" && find empty/.claude creds/.claude -printf '%p %s %m %T@\n' | sort | sha256sum); }
pre="$(snap)"
for h in missing empty creds; do
    echo "## host ~/.claude: $h"
    if (cd "$REPO" && env -u USERPROFILE HOME="$WORK/$h" devcontainer features test -f claude-code-config --skip-autogenerated . >"$WORK/logs-$h.log" 2>&1); then
        ok "scenarios pass with host ~/.claude $h"
    else
        nok "scenarios with host ~/.claude $h (see log)"; grep -E '❌' "$WORK/logs-$h.log" | head
    fi
done
expect "throwaway host ~/.claude dirs untouched" test "$pre" = "$(snap)"
expect "missing host ~/.claude was not created" test ! -e "$WORK/missing/.claude"
finish
